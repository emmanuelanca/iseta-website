/**
 * ISETA chat widget — Deep Chat (https://deepchat.dev) connected to OpenRouter.
 * Injected into every mirrored page; shows a floating button that opens a
 * chat panel backed by the OpenRouter Chat Completion API.
 */
(function () {
  'use strict';

  var OPENROUTER_KEY = 'REDACTED';
  var OPENROUTER_MODEL = 'openai/gpt-4o-mini';
  var DEEP_CHAT_BUNDLE = 'https://unpkg.com/deep-chat@2.5.1/dist/deepChat.bundle.js';

  var scriptEl = document.currentScript;
  var base = scriptEl ? scriptEl.src.slice(0, scriptEl.src.lastIndexOf('/') + 1) : '';

  // documentation retrieval: chunk text index (BM25 fallback) plus a
  // precomputed vector store (docs-vectors.bin, generated by
  // documentation/embed-vectors.js) queried through OpenRouter's
  // embeddings endpoint — semantic retrieval with graceful degradation.
  var MAX_CHUNKS = 10;
  var MAX_PER_SECTION = 2;
  var MIN_SCORE = 1;
  var EMBED_MODEL = 'qwen/qwen3-embedding-8b';
  var EMBED_URL = 'https://openrouter.ai/api/v1/embeddings';
  var COS_THRESHOLD = 0.58; // tuned: chatter tops at ~0.51, doc queries start at ~0.64
  var QUERY_INSTRUCTION =
    'Diagnosticar consultas de estudiantes sobre carreras, materias y documentos oficiales ' +
    'de una institución educativa en Argentina y recuperar fragmentos relevantes de la ' +
    'documentación institucional que respondan la consulta.';

  var docIndex = null; // loaded lazily when the chat opens
  var vecStore = null; // binary vectors, optional (BM25 works without it)

  var STOPWORDS = new Set(
    ('de la el los las un una unos unas unas y o u e en con para por del al que se su sus como mas muy ' +
      'es son ser era fue este esta estos estas estos eso esa esas esas eso eso si no hay también tan ' +
      'cuando donde cuanto sobre entre hasta desde también ya lo me te nos le les más cada todo toda ' +
      'todos todas tanto tiene tienen tiene puede pueden haber está están eso según tal vez muy solo ' +
      'sobre hacer hago hace hacemos dicen')
      .split(' ')
  );

  function stripAccents(s) {
    return s.normalize('NFD').replace(/[\u0300-\u036f]/g, '');
  }

  function tokenize(s) {
    var tokens = stripAccents(String(s).toLowerCase()).match(/[a-z0-9]{3,}/g) || [];
    var out = [];
    for (var i = 0; i < tokens.length; i++) {
      var t = tokens[i];
      if (STOPWORDS.has(t)) continue;
      // crude spanish stemming: shared by index and query so matching stays consistent
      if (t.length >= 6) t = t.replace(/(?:ciones|ciones|s)$/, '');
      else if (t.length >= 5) t = t.replace(/s$/, '');
      out.push(t);
    }
    return out;
  }

  var bm25 = null; // built on first retrieval

  function buildBm25() {
    var docs = docIndex.chunks;
    var df = {}; // document frequency per term
    var docTokens = docs.map(function (c) {
      var tokens = tokenize(c.t + ' ' + (c.h || '') + ' ' + docIndex.docs[c.d].title);
      // dedupe tokens for the document-frequency count only
      var seen = {};
      tokens.forEach(function (t) { seen[t] = 1; });
      Object.keys(seen).forEach(function (t) { df[t] = (df[t] || 0) + 1; });
      return { tokens: tokens, len: tokens.length, bag: seen };
    });
    var avgLen = docTokens.reduce(function (a, d) { return a + d.len; }, 0) / docTokens.length;
    var N = docs.length;
    bm25 = {
      docs: docTokens,
      avgLen: avgLen,
      k1: 1.2,
      b: 0.75,
      idf: function (term) {
        var n = df[term] || 0;
        if (!n) return 0;
        return Math.log((N - n + 0.5) / (n + 0.5) + 1);
      },
    };
  }

  function loadDocs() {
    var loadIndex = fetch(base + 'docs-index.json')
      .then(function (res) { return res.json(); })
      .then(function (json) { docIndex = json; });
    var loadVectors = fetch(base + 'docs-vectors.bin')
      .then(function (res) { return res.arrayBuffer(); })
      .then(function (buf) { parseVecStore(buf); })
      .catch(function () { vecStore = null; }); // BM25 fallback still available
    return Promise.all([loadIndex, loadVectors])
      .catch(function () { docIndex = null; }); // chat still works without docs
  }

  // binary layout: [count: u32LE][dims: u32LE][int8 components per vector]
  function parseVecStore(buffer) {
    var header = new DataView(buffer);
    var count = header.getUint32(0, true);
    var dims = header.getUint32(4, true);
    if ((buffer.byteLength - 8) !== count * dims) {
      throw new Error('bad vector store size');
    }
    vecStore = { count: count, dims: dims, qs: new Int8Array(buffer, 8) };
  }

  function normalizeVec(f32) {
    var norm = 0;
    for (var i = 0; i < f32.length; i++) norm += f32[i] * f32[i];
    norm = Math.sqrt(norm) || 1;
    for (var j = 0; j < f32.length; j++) f32[j] /= norm;
    return f32;
  }

  function embedQuery(text) {
    var input = QUERY_INSTRUCTION + '\nQuery: ' + text;
    return fetch(EMBED_URL, {
      method: 'POST',
      headers: {
        Authorization: 'Bearer ' + OPENROUTER_KEY,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ model: EMBED_MODEL, input: input }),
    })
      .then(function (res) { return res.json(); })
      .then(function (json) {
        if (!json.data || !json.data.length || !Array.isArray(json.data[0].embedding)) {
          throw new Error('unexpected embeddings response');
        }
        return normalizeVec(Float32Array.from(json.data[0].embedding));
      });
  }

  // cosine of the query against every stored vector (dequantized as q/127,
  // the stored vectors were L2-normalized before quantization)
  function semanticScores(queryVec) {
    if (!vecStore) return [];
    var dims = vecStore.dims;
    var qs = vecStore.qs;
    var norm = 0;
    for (var i = 0; i < queryVec.length; i++) norm += queryVec[i] * queryVec[i];
    norm = Math.sqrt(norm) || 1;
    var scored = [];
    for (var v = 0; v < vecStore.count; v++) {
      var base = v * dims;
      var dot = 0;
      for (var j = 0; j < dims; j++) dot += (qs[base + j] / 127) * queryVec[j];
      dot /= norm;
      if (dot >= COS_THRESHOLD) scored.push({ index: v, score: dot });
    }
    scored.sort(function (a, b) { return b.score - a.score; });
    return scored;
  }

  // semantic retrieval: returns [] when the query doesn't relate to the
  // documentation (no injection for casual chatter), or null on failure
  // so the caller can fall back to BM25.
  function retrieveSemantic(query) {
    return embedQuery(query)
      .then(function (queryVec) { return semanticScores(queryVec); })
      .then(function (scored) {
        if (!scored.length) return [];
        var picked = [];
        var perSection = {};
        for (var s = 0; s < scored.length && picked.length < MAX_CHUNKS; s++) {
          var chunk = docIndex.chunks[scored[s].index];
          var key = chunk.d + '|' + chunk.h;
          if ((perSection[key] || 0) >= MAX_PER_SECTION) continue;
          picked.push(chunk);
          perSection[key] = (perSection[key] || 0) + 1;
        }
        return picked;
      });
  }

  function retrieveChunks(query) {
    if (!docIndex) return [];
    if (!bm25) buildBm25();

    var queryTokens = tokenize(query);
    if (!queryTokens.length) return [];

    var scored = [];
    for (var i = 0; i < bm25.docs.length; i++) {
      var d = bm25.docs[i];
      var score = 0;
      var matchedTerms = 0;
      for (var j = 0; j < queryTokens.length; j++) {
        var term = queryTokens[j];
        var freq = 0;
        for (var k = 0; k < d.tokens.length; k++) {
          if (d.tokens[k] === term) freq++;
        }
        if (freq > 0) {
          matchedTerms++;
          var norm = 1 - bm25.b + bm25.b * (d.len / bm25.avgLen);
          score += bm25.idf(term) * ((freq * (bm25.k1 + 1)) / (freq + bm25.k1 * norm));
        }
      }
    // require at least 2 distinct query terms, or a high single-term score,
    // to keep casual chatter ("hola", "gracias") from pulling documents in
    if (score > 0 && (matchedTerms >= 2 || score >= MIN_SCORE)) {
      scored.push({ index: i, score: score });
    }
    }

    if (!scored.length) return [];
    scored.sort(function (a, b) { return b.score - a.score; });

    // take top chunks, at most MAX_PER_SECTION per heading (declares variety)
    var picked = [];
    var perSection = {};
    for (var s = 0; s < scored.length && picked.length < MAX_CHUNKS; s++) {
      var chunk = docIndex.chunks[scored[s].index];
      var key = chunk.d + '|' + chunk.h;
      if ((perSection[key] || 0) >= MAX_PER_SECTION) continue;
      picked.push(chunk);
      perSection[key] = (perSection[key] || 0) + 1;
    }
    return picked;
  }

  function contextMessage(chunks) {
    var parts = ['Documentación oficial del ISETA (fragmentos relevantes para la consulta):', ''];
    chunks.forEach(function (c, i) {
      parts.push('[' + (i + 1) + '] ' + docIndex.docs[c.d].title + (c.h ? ' — Sección: ' + c.h : ''));
      parts.push(c.t);
      parts.push('');
    });
    return parts.join('\n');
  }

  var SYSTEM_SUPPLEMENT =
    'Utilizá la "Documentación oficial" que aparece en el primer mensaje del sistema cuando sea ' +
    'útil para responder la consulta del usuario. Citá de qué documento y sección obtenés la ' +
    'información. Si la información no figura en esos fragmentos, indicá que no está en la ' +
    'documentación cargada y no la inventes.';

  function extractText(content) {
    if (typeof content === 'string') return content;
    if (Array.isArray(content)) {
      return content.filter(function (c) { return c && typeof c.text === 'string'; }).map(function (c) { return c.text; }).join(' ');
    }
    if (content && typeof content.text === 'string') return content.text;
    return '';
  }

  // async is supported by Deep Chat's requestInterceptor: we embed the
  // query through OpenRouter before letting the message through. Failures
  // degrade gracefully (BM25 fallback), never cancelling the user message.
  async function docsInterceptor(details) {
    if (!docIndex || !details || !details.body) return details;
    var messages = details.body.messages;
    if (!Array.isArray(messages)) return details;

    // use the latest user message as the retrieval query
    var query = null;
    for (var i = messages.length - 1; i >= 0; i--) {
      if (messages[i] && messages[i].role === 'user') {
        query = extractText(messages[i].content);
        break;
      }
    }
    if (!query) return details;

    var chunks = null;
    if (vecStore) {
      try {
        chunks = await retrieveSemantic(query);
      } catch (_) {
        chunks = null; // fall through to BM25
      }
    }
    if (chunks === null) chunks = retrieveChunks(query); // BM25 lookahead
    if (!chunks.length) return details;

    messages.unshift({
      role: 'system',
      content: contextMessage(chunks) + '\n\n' + SYSTEM_SUPPLEMENT,
    });
    return details;
  }

  // Load the stylesheet next to this script.
  var cssLink = document.createElement('link');
  cssLink.rel = 'stylesheet';
  cssLink.href = base + 'chat.css';
  cssLink.setAttribute('data-iseta-chat-css', 'true');
  document.head.appendChild(cssLink);

  var panel;
  var panelBody;
  var fab;
  var chatEl;
  var loadingBundle = false;

  var ICON_CHAT =
    '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M12 3C6.6 3 2.2 6.6 2.2 11c0 2.4 1.3 4.5 3.4 6-.2 1.2-.8 2.4-1.9 3.4a.5.5 0 0 0 .4.9c2 0 3.7-.7 5-1.7.9.2 1.9.4 2.9.4 5.4 0 9.8-3.6 9.8-8S17.4 3 12 3zm-4.5 9.2a1.2 1.2 0 1 1 0-2.4 1.2 1.2 0 0 1 0 2.4zm4.5 0a1.2 1.2 0 1 1 0-2.4 1.2 1.2 0 0 1 0 2.4zm4.5 0a1.2 1.2 0 1 1 0-2.4 1.2 1.2 0 0 1 0 2.4z"/></svg>';

  function createWidget() {
    fab = document.createElement('button');
    fab.className = 'iseta-chat-fab';
    fab.setAttribute('aria-label', 'Abrir chat de asistencia');
    fab.innerHTML = ICON_CHAT;
    fab.addEventListener('click', togglePanel);
    document.body.appendChild(fab);

    panel = document.createElement('div');
    panel.className = 'iseta-chat-panel';
    panel.innerHTML =
      '<div class="iseta-chat-header">' +
      '<span>Asistente ISETA</span>' +
      '<button class="iseta-chat-close" aria-label="Cerrar chat">' +
      '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M5 5l14 14M19 5L5 19"/></svg>' +
      '</button>' +
      '</div>' +
      '<div class="iseta-chat-body"></div>';
    panel
      .querySelector('.iseta-chat-close')
      .addEventListener('click', closePanel);
    document.body.appendChild(panel);

    panelBody = panel.querySelector('.iseta-chat-body');
  }

  function togglePanel() {
    if (panel.classList.contains('open')) {
      closePanel();
    } else {
      openPanel();
    }
  }

  function closePanel() {
    panel.classList.remove('open');
    fab.setAttribute('aria-label', 'Abrir chat de asistencia');
  }

  function openPanel() {
    panel.classList.add('open');
    fab.setAttribute('aria-label', 'Cerrar chat de asistencia');

    if (chatEl || loadingBundle) {
      return;
    }
    loadingBundle = true;
    panelBody.innerHTML = '<div class="iseta-chat-loading">Cargando asistente…</div>';

    // load the Deep Chat bundle and the documentation index in parallel
    Promise.all([import(DEEP_CHAT_BUNDLE), loadDocs()])
      .then(function (results) {
        buildChat();
      })
      .catch(function () {
        panelBody.innerHTML =
          '<div class="iseta-chat-loading">No se pudo cargar el chat. Revisá tu conexión e intentá de nuevo.</div>';
      });
  }

  function buildChat() {
    chatEl = document.createElement('deep-chat');
    chatEl.directConnection = {
      openRouter: {
        key: OPENROUTER_KEY,
        model: OPENROUTER_MODEL,
        system_prompt:
          'Sos el asistente virtual del ISETA (Instituto Superior Experimental de Tecnología ' +
          'Alimentaria). Respondé consultas sobre la institución amablemente y hablando en voseo. ' +
          'Si no sabés algo específico de la institución o el usuario pregunta algo no relacionado a la ' +
          'institución, amablemente no respondas la pregunta.',
        max_tokens: 1024,
      },
    };
    chatEl.stream = true;
    chatEl.introMessage = {
      text:
        '¡Hola! 👋 Soy el asistente virtual del ISETA. Podés preguntarme lo que quieras ' +
        'sobre la institución y las carreras.',
    };
    chatEl.textInput = {
      placeholder: { text: 'Escribí tu pregunta…' },
    };

    // Scrollbars: styled scrollbar inside the component (shadow DOM) and a
    // scrollable message area within the fixed-panel height.
    chatEl.auxiliaryStyle = [
      '::-webkit-scrollbar { width: 8px; }',
      '::-webkit-scrollbar-track { background: transparent; }',
      '::-webkit-scrollbar-thumb { background: rgba(0, 0, 0, 0.22); border-radius: 6px; }',
      '::-webkit-scrollbar-thumb:hover { background: rgba(0, 0, 0, 0.38); }',
      '* { scrollbar-width: thin; scrollbar-color: rgba(0, 0, 0, 0.28) transparent; }',
    ].join('\n');
    chatEl.requestBodyLimits = { maxMessages: 12 };

    // documentation retrieval: inject relevant chunks of the official
    // curricular decrees into the request to OpenRouter
    chatEl.requestInterceptor = docsInterceptor;

    chatEl.errorMessages = {
      displayServiceErrorMessages: true,
    };

    panelBody.innerHTML = '';
    panelBody.appendChild(chatEl);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', createWidget);
  } else {
    createWidget();
  }
})();
